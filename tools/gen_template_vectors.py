"""Regenerates vectors/template_vectors.json from the Python template encoder.

Run from the repo root after adding a case:  python tools/gen_template_vectors.py
Every other encoder (the app's, a board's) must then produce the same bytes.
"""
import json

from allsense_testkit.template import Template
cases = [
  {"template": json.load(open("templates/my_robot_imu.json")),
   "values": {"accelerometer": [0.12, 9.81, -0.33], "gyroscope": [0.01, -0.002, 1.5]}, "seq": 7},
  {"template": {"name": "big_endian_floats", "header": "24 41 53", "rate_hz": 20, "endian": "big",
                "fields": [{"src": "pressure", "type": "f32"}, {"src": "light", "idx": 0, "type": "u16", "scale": 10},
                           {"type": "seq_u16"}, {"type": "const", "bytes": "0D 0A"}],
                "checksum": "crc16_ccitt", "checksum_covers": "all"},
   "values": {"pressure": [1013.25], "light": [123.5]}, "seq": 70000},
  {"template": {"name": "clamp_and_nan", "rate_hz": 10,
                "fields": [{"src": "accelerometer", "idx": [0, 1, 2], "type": "u8", "scale": 10, "offset": 128},
                           {"src": "accelerometer", "idx": [0], "type": "i32", "scale": 1000000}],
                "checksum": "sum8"},
   "values": {"accelerometer": [100.0, -100.0, None]}, "seq": 0},
  {"template": {"name": "crc8_check", "header": "7E", "rate_hz": 50,
                "fields": [{"src": "gyroscope", "idx": [2, 0], "type": "i16", "scale": 100}, {"type": "seq_u8"}],
                "checksum": "crc8"},
   "values": {"gyroscope": [-1.25, 0.5, 2.75]}, "seq": 300},
]
for c in cases:
    c["hex"] = Template(c["template"]).encode(c["values"], c["seq"]).hex()
json.dump({"note": "Generated by tools/gen_template_vectors.py; every template encoder must produce these bytes.", "cases": cases},
          open("vectors/template_vectors.json", "w"), indent=1)
for c in cases: print(c["template"]["name"], c["hex"])
